  '⻈': '讠', '⺟': '母', '⺫': '目', '⺮': '竹', '⻁': '虎', '⻣': '骨', '⻤': '鬼', '⻬': '齐', '⻮': '齿', '⻭': '齿',
  '⺁': '厂', '⺇': '几', '⺋': '卩', '⺍': '小', '⺕': '彐', '⺗': '心', '⺧': '牛', '⺩': '王', '⺪': '疋', '⺬': '示',
